"""Turning raw judged pairs into a repeatable selection: kept, split, and the mini set.

The data here is a small invented table, generated by arithmetic so every test can say exactly
what it expects. No download, no pandas, no randomness: the same input gives the same answer.
"""

import hashlib
import json
from dataclasses import replace
from pathlib import Path

import pytest

from eval.dataset import (
    DATASET_REPO,
    DATASET_REVISION,
    ManifestMismatch,
    Pair,
    Product,
    Selection,
    SelectionConfig,
    add_distractors_to_mini_selection,
    dedupe_and_check_products,
    pick_mini_test_queries,
    pick_queries_and_assign_buckets,
    restrict,
    stable_rank,
    verify_dataset,
    write_dataset,
)

# 40 english queries: 0 to 29 come from the train file and 30 to 39 from the test file
# every query has 5 judged products out of a pool of 60, and the pools overlap between queries
TRAIN_QUERIES = range(0, 30)
TEST_QUERIES = range(30, 40)
LABELS = "ESCI"


def pair(query_id: int, j: int, **changes: object) -> Pair:
    base = Pair(
        query_id=query_id,
        query=f"query {query_id}",
        product_id=f"P{(query_id * 7 + j * 3) % 60:03d}",
        locale="us",
        label=LABELS[(query_id + j) % 4],
        small_version=1,
        dataset_split="train" if query_id in TRAIN_QUERIES else "test",
    )
    return replace(base, **changes)


def raw_pairs() -> list[Pair]:
    wanted = [pair(q, j) for q in [*TRAIN_QUERIES, *TEST_QUERIES] for j in range(5)]
    # rows the selection must throw away: another language, and outside the small version
    noise = [pair(100 + q, 0, locale="es") for q in range(5)]
    noise += [pair(200 + q, 0, small_version=0) for q in range(5)]
    return wanted + noise


CONFIG = SelectionConfig(
    seed=1, target_products=50, validation_share=0.2, mini_queries=3, mini_products=25
)


def judgements_of(selection: Selection, query_id: int) -> dict[str, str]:
    return {j.product_id: j.label for j in selection.judgements if j.query_id == query_id}


@pytest.fixture
def selection() -> Selection:
    return pick_queries_and_assign_buckets(raw_pairs(), CONFIG)


# the order that is the same on every machine


def test_the_stable_rank_is_a_number_made_from_a_hash_of_the_seed_the_salt_and_the_key() -> None:
    digest = hashlib.sha256(b"7:queries:42").digest()
    assert stable_rank(7, "queries", "42") == int.from_bytes(digest[:8], "big")


def test_the_stable_rank_changes_with_the_seed_the_salt_and_the_key() -> None:
    ranks = {stable_rank(s, salt, key) for s in (1, 2) for salt in ("a", "b") for key in ("x", "y")}
    assert len(ranks) == 8


# what is kept from the raw rows


def test_only_english_rows_of_the_small_version_are_kept() -> None:
    kept = restrict(raw_pairs(), CONFIG)
    assert {p.locale for p in kept} == {"us"}
    assert {p.small_version for p in kept} == {1}
    assert len(kept) == 200  # the 40 queries x 5 products, none of the noise


def test_a_label_that_is_not_e_s_c_or_i_is_refused() -> None:
    with pytest.raises(ValueError, match="label"):
        restrict([pair(0, 0, label="X")], CONFIG)


def test_the_same_pair_twice_collapses_but_two_labels_for_one_pair_are_refused() -> None:
    assert len(restrict([pair(0, 0), pair(0, 0)], CONFIG)) == 1
    with pytest.raises(ValueError, match="two labels"):
        restrict([pair(0, 0, label="E"), pair(0, 0, label="I")], CONFIG)


def test_a_query_found_in_both_the_train_and_the_test_file_is_refused() -> None:
    leaking = [pair(0, 0), pair(0, 1, dataset_split="test")]
    with pytest.raises(ValueError, match="both"):
        pick_queries_and_assign_buckets(leaking, CONFIG)


# which queries are selected


def test_queries_are_added_until_enough_distinct_products_are_covered(
    selection: Selection,
) -> None:
    assert len(selection.product_ids) >= CONFIG.target_products
    assert len(selection.queries) < 40  # it stopped, it did not take everything


def test_every_judged_product_of_a_selected_query_is_kept(selection: Selection) -> None:
    everything = restrict(raw_pairs(), CONFIG)
    for query in selection.queries:
        expected = {p.product_id: p.label for p in everything if p.query_id == query.query_id}
        assert judgements_of(selection, query.query_id) == expected


def test_a_product_shared_by_several_selected_queries_is_listed_once(
    selection: Selection,
) -> None:
    assert len(selection.product_ids) == len(set(selection.product_ids))
    judged = {j.product_id for j in selection.judgements}
    assert set(selection.product_ids) == judged
    assert len(selection.judgements) > len(judged)  # the pools overlap, so products repeat


def test_a_small_pool_is_taken_whole_when_it_is_smaller_than_the_target() -> None:
    few = [pair(q, j) for q in range(3) for j in range(2)]
    everything = pick_queries_and_assign_buckets(few, replace(CONFIG, target_products=1000))
    assert len(everything.queries) == 3


def test_the_same_seed_gives_the_same_selection_whatever_the_order_of_the_rows(
    selection: Selection,
) -> None:
    shuffled = list(reversed(raw_pairs()))
    assert pick_queries_and_assign_buckets(shuffled, CONFIG) == selection


def test_another_seed_selects_other_queries(selection: Selection) -> None:
    other = pick_queries_and_assign_buckets(raw_pairs(), replace(CONFIG, seed=2))
    assert {q.query_id for q in other.queries} != {q.query_id for q in selection.queries}


# the split by query


def test_no_query_is_in_two_buckets(selection: Selection) -> None:
    ids = [q.query_id for q in selection.queries]
    assert len(ids) == len(set(ids))
    assert {q.split for q in selection.queries} <= {"train", "validation", "test"}


def test_the_test_queries_of_the_dataset_stay_test_and_validation_comes_only_from_train(
    selection: Selection,
) -> None:
    for query in selection.queries:
        from_test_file = query.query_id in TEST_QUERIES
        assert (query.split == "test") == from_test_file


def test_a_validation_share_of_zero_makes_none_and_a_share_of_one_makes_all_of_train() -> None:
    none = pick_queries_and_assign_buckets(
        raw_pairs(), replace(CONFIG, validation_share=0.0, target_products=1000)
    )
    assert "validation" not in {q.split for q in none.queries}
    every = pick_queries_and_assign_buckets(
        raw_pairs(), replace(CONFIG, validation_share=1.0, target_products=1000)
    )
    assert "train" not in {q.split for q in every.queries}
    assert {q.split for q in every.queries} == {"validation", "test"}


def test_the_validation_queries_are_the_same_on_every_run() -> None:
    config = replace(CONFIG, target_products=1000, validation_share=0.3)
    first = {
        q.query_id
        for q in pick_queries_and_assign_buckets(raw_pairs(), config).queries
        if q.split == "validation"
    }
    again = {
        q.query_id
        for q in pick_queries_and_assign_buckets(list(reversed(raw_pairs())), config).queries
        if q.split == "validation"
    }
    assert first == again
    assert 0 < len(first) < 30


# the mini set


@pytest.fixture
def mini(selection: Selection) -> Selection:
    return add_distractors_to_mini_selection(selection, CONFIG)


def test_the_mini_set_has_the_asked_number_of_queries_all_from_the_test_split(
    mini: Selection,
) -> None:
    assert len(mini.queries) == CONFIG.mini_queries
    assert {q.split for q in mini.queries} == {"test"}


def test_the_mini_set_keeps_every_judged_product_of_its_queries(
    selection: Selection, mini: Selection
) -> None:
    for query in mini.queries:
        assert judgements_of(mini, query.query_id) == judgements_of(selection, query.query_id)


def test_the_mini_set_has_the_asked_number_of_products_judged_ones_plus_distractors(
    selection: Selection, mini: Selection
) -> None:
    judged = {j.product_id for j in mini.judgements}
    assert len(mini.product_ids) == CONFIG.mini_products
    distractors = set(mini.product_ids) - judged
    assert distractors  # there are some
    assert distractors.isdisjoint(judged)  # and none of them is judged for the mini queries
    assert set(mini.product_ids) <= set(selection.product_ids)


def test_the_mini_set_is_the_same_on_every_run(selection: Selection, mini: Selection) -> None:
    assert add_distractors_to_mini_selection(selection, CONFIG) == mini
    other = add_distractors_to_mini_selection(selection, replace(CONFIG, seed=2))
    assert {q.query_id for q in other.queries} != {q.query_id for q in mini.queries} or (
        set(other.product_ids) != set(mini.product_ids)
    )


def test_too_few_test_queries_for_the_mini_set_is_an_error(selection: Selection) -> None:
    with pytest.raises(ValueError, match="test queries"):
        add_distractors_to_mini_selection(selection, replace(CONFIG, mini_queries=99))


def test_a_mini_set_too_small_to_hold_the_judged_products_is_an_error(
    selection: Selection,
) -> None:
    with pytest.raises(ValueError, match="mini_products"):
        add_distractors_to_mini_selection(selection, replace(CONFIG, mini_products=2))


# the product table


def product(product_id: str, title: str = "t") -> Product:
    return Product(
        product_id=product_id,
        locale="us",
        title=title,
        description=None,
        bullet_point=None,
        brand=None,
        color=None,
    )


def test_products_are_deduplicated_sorted_and_limited_to_the_ones_asked_for() -> None:
    rows = [product("B"), product("A"), product("B"), product("C")]
    assert [p.product_id for p in dedupe_and_check_products(["B", "A"], rows)] == ["A", "B"]


def test_a_product_with_no_text_is_an_error() -> None:
    with pytest.raises(ValueError, match="missing"):
        dedupe_and_check_products(["A", "Z"], [product("A")])


# files and the manifest


def written(directory: Path, selection: Selection) -> dict[str, object]:
    products = [product(pid, title=f"title of {pid}") for pid in selection.product_ids]
    return write_dataset(directory, selection, products, CONFIG, dataset_revision=1)


def test_the_files_and_the_manifest_are_written_and_verify(
    tmp_path: Path, selection: Selection
) -> None:
    manifest = written(tmp_path, selection)
    assert sorted(path.name for path in tmp_path.iterdir()) == [
        "judgements.jsonl",
        "manifest.json",
        "products.jsonl",
        "queries.jsonl",
    ]
    verify_dataset(tmp_path)  # no error
    assert manifest["dataset"] == {"repo": DATASET_REPO, "revision": DATASET_REVISION}
    assert manifest["dataset_revision"] == 1
    assert manifest["config"]["seed"] == 1  # type: ignore[index]
    assert manifest["counts"]["queries"] == len(selection.queries)  # type: ignore[index]
    assert json.loads((tmp_path / "manifest.json").read_text(encoding="utf-8")) == manifest


def test_writing_twice_gives_byte_identical_files(tmp_path: Path, selection: Selection) -> None:
    first, second = tmp_path / "one", tmp_path / "two"
    first.mkdir()
    second.mkdir()
    a, b = written(first, selection), written(second, selection)
    assert a == b  # the same hashes in the manifest
    for name in ("queries.jsonl", "judgements.jsonl", "products.jsonl"):
        assert (first / name).read_bytes() == (second / name).read_bytes()


def test_one_changed_byte_in_any_file_fails_the_check_and_names_the_file(
    tmp_path: Path, selection: Selection
) -> None:
    written(tmp_path, selection)
    target = tmp_path / "judgements.jsonl"
    data = bytearray(target.read_bytes())
    data[10] ^= 1  # flip one bit
    target.write_bytes(bytes(data))
    with pytest.raises(ManifestMismatch, match=r"judgements\.jsonl"):
        verify_dataset(tmp_path)


def test_a_missing_file_fails_the_check(tmp_path: Path, selection: Selection) -> None:
    written(tmp_path, selection)
    (tmp_path / "products.jsonl").unlink()
    with pytest.raises(ManifestMismatch, match=r"products\.jsonl"):
        verify_dataset(tmp_path)


def test_the_files_hold_one_json_object_per_line_sorted_by_key(
    tmp_path: Path, selection: Selection
) -> None:
    written(tmp_path, selection)
    lines = (tmp_path / "queries.jsonl").read_text(encoding="utf-8").splitlines()
    rows = [json.loads(line) for line in lines]
    assert [r["query_id"] for r in rows] == sorted(r["query_id"] for r in rows)
    assert set(rows[0]) == {"query_id", "query", "split"}


def test_the_products_file_is_the_same_whatever_order_the_products_arrive_in(
    tmp_path: Path, selection: Selection
) -> None:
    in_order = [product(pid, title=f"title of {pid}") for pid in selection.product_ids]
    first, second = tmp_path / "one", tmp_path / "two"
    first.mkdir()
    second.mkdir()
    write_dataset(first, selection, in_order, CONFIG, dataset_revision=1)
    write_dataset(second, selection, list(reversed(in_order)), CONFIG, dataset_revision=1)
    assert (first / "products.jsonl").read_bytes() == (second / "products.jsonl").read_bytes()


# the mini set can be told which products it may use as distractors


def test_the_choice_of_mini_queries_is_the_same_one_build_mini_uses(
    selection: Selection, mini: Selection
) -> None:
    queries, judgements = pick_mini_test_queries(selection, CONFIG)
    assert queries == mini.queries
    assert judgements == mini.judgements


def test_distractors_come_only_from_the_pool_when_a_pool_is_given(selection: Selection) -> None:
    _, judgements = pick_mini_test_queries(selection, CONFIG)
    judged = {j.product_id for j in judgements}
    others = [p for p in selection.product_ids if p not in judged]
    pool = set(others[:15])  # enough for the 25 - judged distractors we need
    needed = CONFIG.mini_products - len(judged)
    small = replace(CONFIG, mini_products=len(judged) + min(needed, len(pool)))
    mini = add_distractors_to_mini_selection(selection, small, product_ids_in_planned_blocks=pool)
    assert set(mini.product_ids) - judged <= pool


def test_a_pool_too_small_for_the_distractors_is_an_error(selection: Selection) -> None:
    with pytest.raises(ValueError, match="distractors"):
        add_distractors_to_mini_selection(selection, CONFIG, product_ids_in_planned_blocks=set())


def test_the_manifest_records_the_source_files_it_was_built_from(
    tmp_path: Path, selection: Selection
) -> None:
    sources = [{"name": "data/test-0.parquet", "split": "test", "size": 10, "sha256": "a" * 64}]
    products = [product(pid) for pid in selection.product_ids]
    manifest = write_dataset(
        tmp_path, selection, products, CONFIG, dataset_revision=1, sources=sources
    )
    assert manifest["source_files"] == sources
